/**
 * Generates React icon components from Material Symbols (Outlined, weight 300 — design system v2).
 *
 *   npm run icons
 *
 * To add an icon: put its Material Symbols name in ICONS below and re-run. Browse names at
 * https://fonts.google.com/icons (Outlined, weight 300). Output: app/_component/icons/material.tsx
 * Each icon renders an inline SVG in currentColor, so it sizes with `size-*` classes like any SVG.
 * Pass `filled` for the filled variant (used for the active nav item).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'node_modules/@material-symbols/svg-300/outlined');
const OUT = join(ROOT, 'app/_component/icons/material.tsx');

// Font ligature names that the SVG package stores under another name.
const ALIASES = {
    expand_more: 'keyboard_arrow_down',
    expand_less: 'keyboard_arrow_up',
    auto_awesome: 'star_shine'
};

// prettier-ignore
const ICONS = [
    // Navigation & chrome
    'add', 'add_circle', 'apps', 'arrow_back', 'arrow_downward', 'arrow_forward', 'arrow_upward',
    'chevron_left', 'chevron_right', 'close', 'drag_indicator', 'expand_less', 'expand_more',
    'filter_list', 'home', 'hub', 'left_panel_close', 'left_panel_open', 'logout', 'menu',
    'more_horiz', 'more_vert', 'notifications', 'open_in_new', 'refresh', 'search', 'search_off',
    'settings', 'unfold_more',
    // Status & feedback
    'block', 'bolt', 'check', 'check_circle', 'cloud_off', 'error', 'help', 'info', 'lock',
    'progress_activity', 'remove', 'sync', 'warning', 'wifi_off',
    // Sessions & editor
    'arrow_outward', 'arrow_selector_tool', 'attach_file', 'auto_awesome', 'blur_on', 'bug_report', 'calendar_today',
    'chat_bubble', 'content_copy', 'crop_square', 'delete', 'download', 'draw', 'edit', 'folder_open',
    'image', 'link', 'mail', 'pause', 'play_arrow', 'play_circle', 'schedule', 'screenshot_region',
    'send', 'star', 'terminal', 'title', 'upload_file', 'videocam', 'visibility',
    // Properties
    'person', 'person_add', 'group', 'radio_button_checked', 'radio_button_unchecked',
    'signal_cellular_alt', 'signal_cellular_alt_1_bar', 'signal_cellular_alt_2_bar',
    // Theme & devices
    'computer', 'dark_mode', 'desktop_windows', 'domain', 'extension', 'light_mode', 'screen_record',
    'spellcheck', 'timer', 'touch_app', 'verified', 'verified_user',
    'text_fields', 'view_column'
];

const pascal = (name) =>
    name
        .split('_')
        .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
        .join('')
        .replace(/^(\d)/, 'N$1') + 'Icon';

const readPath = (file) => {
    const svg = readFileSync(file, 'utf8');
    const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
    if (!paths.length) throw new Error(`No <path> in ${file}`);
    return paths.join(' ');
};

const missing = [];
const lines = [];
for (const name of [...new Set(ICONS)].sort()) {
    const source = ALIASES[name] ?? name;
    const file = join(SRC, `${source}.svg`);
    if (!existsSync(file)) {
        missing.push(name);
        continue;
    }
    const fillFile = join(SRC, `${source}-fill.svg`);
    const outline = readPath(file);
    const filledPath = existsSync(fillFile) ? readPath(fillFile) : null;
    const fill = filledPath && filledPath !== outline ? filledPath : null;
    lines.push(
        `export const ${pascal(name)} = createIcon('${pascal(name)}', '${outline}'${fill ? `, '${fill}'` : ''});`
    );
}

if (missing.length) {
    console.error(`Unknown Material Symbols names: ${missing.join(', ')}`);
    process.exit(1);
}

const header = `// GENERATED by scripts/generate-icons.mjs from @material-symbols/svg-300 (Outlined, weight 300).
// Do not edit by hand: add the icon name to ICONS in the script and run \`npm run icons\`.
import * as React from 'react';

export type IconProps = React.SVGProps<SVGSVGElement> & {
    /** Filled variant (design system: active nav item only). */
    filled?: boolean;
};

function createIcon(displayName: string, d: string, filledD?: string) {
    function Icon({ filled = false, ...props }: IconProps) {
        return (
            <svg
                xmlns="http://www.w3.org/2000/svg"
                viewBox="0 -960 960 960"
                width={24}
                height={24}
                fill="currentColor"
                aria-hidden
                focusable={false}
                data-icon={displayName}
                {...props}>
                <path d={filled && filledD ? filledD : d} />
            </svg>
        );
    }
    Icon.displayName = displayName;
    return Icon;
}
`;

writeFileSync(OUT, `${header}\n${lines.join('\n')}\n`);
console.log(`Wrote ${lines.length} icons to ${OUT}`);
